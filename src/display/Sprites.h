// Helper: get frame count for given mood/stage
inline uint8_t getSpriteFrameCount(uint8_t moodIndex, bool isAdult) {
    const SpriteFrame (*table)[4] = isAdult ? ADULT_SPRITES : BABY_SPRITES;
    uint8_t count = 0;
    for (int i = 0; i < 4; i++) {
        if (table[moodIndex][i].data != nullptr) count++;
        else break;
    }
    return count ? count : 1;
}
